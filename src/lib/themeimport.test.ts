test('garbage, empty and wrong-shape inputs fail with a clear error and never throw', () => {
  assert.match(fail(parseTheme('hello world, this is not a theme')), /Unrecognized theme format.*Windows Terminal.*iTerm2.*Alacritty/);
  assert.match(fail(parseTheme('')), /empty/);
  assert.match(fail(parseTheme('   \n\t ')), /empty/);
  assert.match(fail(parseTheme('{"a": ')), /JSON/);
  assert.match(fail(parseTheme('[1,2,3]')), /No color schemes/);
  assert.match(fail(parseTheme('{"foo":"bar"}')), /No color schemes/);
  assert.match(fail(parseTheme('<html><body>hi</body></html>')), /Unrecognized/);
  assert.match(fail(parseTheme('<plist><dict></dict></plist>')), /No iTerm2 colors/);
  assert.match(fail(parseTheme('[colors.primary]\n')), /Alacritty/);
  for (const junk of ['\u0000\u0001', '}{', '"', '[[[[', '<<<>>>', 'null', '123', '\uFEFF']) {
    assert.doesNotThrow(() => parseTheme(junk));
    assert.equal(parseTheme(junk).ok, false);
  }
  assert.equal(parseTheme(undefined as unknown as string).ok, false);
});

