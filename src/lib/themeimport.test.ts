function ok(r: ParseResult) {
  assert.equal(r.ok, true, r.ok ? '' : r.error);
  if (!r.ok) throw new Error(r.error);
  return r;
}
function fail(r: ParseResult) {
  assert.equal(r.ok, false);
  if (r.ok) throw new Error('expected failure');
  return r.error;
}
