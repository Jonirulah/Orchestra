/** Genera un .itermcolors con el mismo molde que escribe iTerm2 (Alpha, Blue, Color Space, Green, Red). */
function itermColor(hex: string): string {
  const f = (i: number) => (parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(10);
  return `\t<dict>
\t\t<key>Alpha Component</key>
\t\t<real>1</real>
\t\t<key>Blue Component</key>
\t\t<real>${f(5)}</real>
\t\t<key>Color Space</key>
\t\t<string>sRGB</string>
\t\t<key>Green Component</key>
\t\t<real>${f(3)}</real>
\t\t<key>Red Component</key>
\t\t<real>${f(1)}</real>
\t</dict>`;
}
function itermFile(ansi: string[], bg: string, fg: string, cursor: string, sel: string): string {
  const parts: string[] = [];
  ansi.forEach((h, i) => parts.push(`\t<key>Ansi ${i} Color</key>\n${itermColor(h)}`));
  parts.push(`\t<key>Background Color</key>\n${itermColor(bg)}`);
  parts.push(`\t<key>Cursor Color</key>\n${itermColor(cursor)}`);
  parts.push(`\t<key>Foreground Color</key>\n${itermColor(fg)}`);
  parts.push(`\t<key>Selection Color</key>\n${itermColor(sel)}`);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
${parts.join('\n')}
</dict>
</plist>
`;
}

