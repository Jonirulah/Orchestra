test('withUniqueIds avoids ids already saved and does not mutate the input', () => {
  const a = ok(parseTheme(DRACULA_ORCHESTRA)).themes;
  const saved = withUniqueIds(a, []);
  assert.equal(saved[0].id, 'custom:dracula');
  const again = withUniqueIds(a, saved);
  assert.equal(again[0].id, 'custom:dracula-2');
  const third = withUniqueIds(a, [...saved, ...again]);
  assert.equal(third[0].id, 'custom:dracula-3');
  assert.equal(a[0].id, 'custom:dracula');
});

